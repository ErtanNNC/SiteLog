import { describe, expect, it } from 'vitest';
import { deriveTotals } from '@sitelog/shared';
import { heroReportData } from '@sitelog/pdf/sample-data.ts';
import {
  evidencePackReadyEmail,
  invoiceQueryEmail,
  reportEditedAfterSignoffEmail,
  reportFiledEmail,
  reportMissingEmail,
  unknownContactEmail,
  weeklyDigestEmail,
} from './templates';

const EMOJI = /[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}]/u;

describe('email templates', () => {
  it('report_filed uses the §13 subject and lists crew, hours, weather', () => {
    const e = reportFiledEmail({
      kind: 'report_filed',
      orgName: 'Kestrel Build Group',
      siteName: 'Riverside Lofts — Block B',
      reportNo: 'RL-2041-0187',
      reportDate: '2026-10-09',
      version: 1,
      changeNote: null,
      summary: heroReportData.summary,
      totals: deriveTotals(heroReportData),
      reviewReasons: [],
      isLate: false,
      reporterFirstName: 'Marco',
      url: 'https://app.talkolog.com/reports/x',
    });
    expect(e.subject).toBe('Daily report · Riverside Lofts · Fri Oct 9 · RL-2041-0187');
    expect(e.text).toContain('Crew: 24 on site · 5 subs');
    expect(e.text).toContain('Hours: 192 h');
    expect(e.html).toContain('Open in TalkOlog');
    expect(e.html).not.toMatch(EMOJI);
    // W1-15: the footer names no channel.
    expect(e.html).toContain('Generated by TalkOlog from a voice report.');
    expect(e.html + e.text).not.toMatch(/WhatsApp/);
  });

  it('report_filed in Turkish: the §13 TR subject, labels and hours (W1-15)', () => {
    const e = reportFiledEmail({
      kind: 'report_filed',
      language: 'tr',
      orgName: 'Demir Yapı A.Ş.',
      siteName: 'Kartal Konutları — B Blok',
      reportNo: 'KK-3307-0042',
      reportDate: '2026-10-09',
      version: 1,
      changeNote: null,
      summary: '',
      totals: deriveTotals(heroReportData),
      reviewReasons: ['unconfirmed', 'unknown_company:Yıldız'],
      isLate: true,
      reporterFirstName: 'Emre',
      url: 'https://app.talkolog.com/reports/x',
    });
    expect(e.subject).toBe('Günlük rapor · Kartal Konutları · Cum 9 Eki · KK-3307-0042');
    expect(e.text).toContain('Ekip: Sahada 24 kişi · 5 taşeron');
    expect(e.text).toContain('Saat: 192 sa');
    expect(e.html).toContain('Raporlayan');
    expect(e.text).toContain('Hava: Hava nedeniyle 3,5 sa kayıp');
    expect(e.text).toContain('- Onaysız kaydedildi');
    expect(e.text).toContain('- Bilinmeyen taşeron: Yıldız');
    expect(e.text).toContain('Özet yok.');
    expect(e.text).toContain('PDF ektedir.');
    expect(e.html).toContain('TalkOlog tarafından sesli bir rapordan oluşturuldu.');
    expect(e.html).toContain('İnceleme gerekli');
    expect(e.html).not.toMatch(/WhatsApp/);
  });

  it('report_updated shows the change note and review reasons', () => {
    const e = reportFiledEmail({
      kind: 'report_updated',
      orgName: 'K',
      siteName: 'Oakmont Medical Center',
      reportNo: 'OM-1187-0120',
      reportDate: '2026-10-09',
      version: 2,
      changeNote: 'Apex Concrete 6 → 7 workers',
      summary: 's',
      totals: deriveTotals(heroReportData),
      reviewReasons: ['unknown_company:Ridgeway'],
      isLate: true,
      reporterFirstName: null,
      url: 'u',
    });
    expect(e.subject).toContain('Updated: OM-1187-0120');
    expect(e.text).toContain('Updated: Apex Concrete 6 → 7 workers');
    expect(e.text).toContain('Unknown subcontractor: Ridgeway');
    expect(e.html).toContain('Needs review');
    expect(e.html).toContain('Late');
  });

  it('other kinds render subject, text and html without emoji', () => {
    const all = [
      reportMissingEmail({
        orgName: 'K',
        siteName: 'Elm St. Townhomes',
        date: '2026-10-09',
        reporterFirstName: 'Priya',
        reporterPhone: '+15550147719',
        url: 'u',
      }),
      invoiceQueryEmail({
        orgName: 'K',
        companyName: 'BrightLine Electric',
        invoiceNo: 'BL-3381',
        periodStart: '2026-10-05',
        periodEnd: '2026-10-09',
        invoicedHours: 212,
        reportedHours: 196,
        url: 'u',
      }),
      evidencePackReadyEmail({
        orgName: 'K',
        siteName: 'Riverside Lofts — Block B',
        periodStart: '2026-10-01',
        periodEnd: '2026-10-09',
        downloadUrl: 'https://x/signed',
        panelUrl: 'u',
      }),
      weeklyDigestEmail({
        orgName: 'K',
        weekStart: '2026-10-05',
        weekEnd: '2026-10-11',
        stats: {
          siteDays: 30,
          filed: 29,
          onTime: 27,
          weatherHoursBySite: [{ siteName: 'Riverside', hours: 7 }],
          unsigned: [{ reportNo: 'RL-2041-0187', siteName: 'Riverside', date: '2026-10-09' }],
          invoiceGaps: [{ companyName: 'BrightLine Electric', gap: 16 }],
        },
        url: 'u',
      }),
      unknownContactEmail({
        orgName: 'K',
        phone: '+15550194410',
        snippet: 'this is Luis, covering Elm St. today',
        url: 'u',
      }),
      reportEditedAfterSignoffEmail({
        orgName: 'K',
        reportNo: 'RL-2041-0187',
        changeNote: 'Apex 6 → 7',
        version: 2,
        url: 'u',
      }),
    ];
    for (const e of all) {
      expect(e.subject.length).toBeGreaterThan(5);
      expect(e.text.length).toBeGreaterThan(20);
      expect(e.html).toContain('<!doctype html>');
      expect(e.html).not.toMatch(EMOJI);
      expect(e.text).not.toMatch(EMOJI);
    }
    expect(all[0]!.text).toContain("Priya hasn't sent the report for");
    expect(all[0]!.text).toContain('the deadline has passed');
    expect(all[0]!.text).not.toContain('reminder');
    expect(all[1]!.text).toContain('Difference: +16 h');
    expect(all[3]!.subject).toContain('90% on time');
  });

  it('report_missing names the reminders the ladder sent (§13, W2-06)', () => {
    const base = {
      orgName: 'K',
      siteName: 'Elm St. Townhomes',
      date: '2026-10-09',
      reporterFirstName: 'Priya',
      reporterPhone: null,
      url: 'u',
    };
    expect(reportMissingEmail({ ...base, reminders: 2 }).text).toContain(
      "Elm St. Townhomes — no report. Priya didn't answer 2 reminders.",
    );
    expect(reportMissingEmail({ ...base, reminders: 1 }).text).toContain(
      "Priya didn't answer 1 reminder.",
    );
    expect(reportMissingEmail({ ...base, reminders: 0 }).text).toContain(
      "Priya hasn't sent the report for",
    );
  });
});

describe('office email templates in Turkish (W4-09, §19 Q239)', () => {
  const TR = 'tr' as const;

  it('report_missing: Turkish subject, line, chip and call link', () => {
    const base = {
      language: TR,
      orgName: 'Demir Yapı A.Ş.',
      siteName: 'Kartal Konutları — B Blok',
      date: '2026-10-09',
      reporterFirstName: 'Emre',
      reporterPhone: '+905321234567',
      url: 'u',
    };
    const e = reportMissingEmail({ ...base, reminders: 2 });
    expect(e.subject).toBe('Kartal Konutları — rapor yok · Cum 9 Eki');
    expect(e.text).toContain(
      'Kartal Konutları — B Blok — rapor yok. Emre 2 hatırlatmaya yanıt vermedi.',
    );
    expect(e.text).toContain('Ara: Emre, +905321234567');
    expect(e.text).toContain('TalkOlog’da aç: u');
    expect(e.html).toContain('Eksik');
    expect(e.html).toContain('<title>Rapor yok</title>');
    expect(reportMissingEmail({ ...base, reporterFirstName: null }).text).toContain(
      'Şantiye şefi Cum 9 Eki raporunu göndermedi ve son saat geçti.',
    );
    for (const s of [e.html, e.text]) expect(s).not.toMatch(/no report|Missing|Open in TalkOlog/);
  });

  it('invoice_query: Turkish hours and difference', () => {
    const e = invoiceQueryEmail({
      language: TR,
      orgName: 'Demir Yapı A.Ş.',
      companyName: 'Yıldız Elektrik',
      invoiceNo: null,
      periodStart: null,
      periodEnd: null,
      invoicedHours: 212,
      reportedHours: 196,
      url: 'u',
    });
    expect(e.subject).toBe('Saat sorgusu · Yıldız Elektrik');
    expect(e.text).toContain(
      'Demir Yapı A.Ş., faturayı fatura dönemine ait günlük şantiye raporlarıyla karşılaştırdı.',
    );
    expect(e.text).toContain('Faturalanan: 212 sa');
    expect(e.text).toContain('Fark: +16 sa');
    expect(e.html).toContain('TalkOlog ile gönderildi.');
  });

  it('evidence_pack_ready: Turkish, and all sites when the pack has none', () => {
    const e = evidencePackReadyEmail({
      language: TR,
      orgName: 'Demir Yapı A.Ş.',
      siteName: null,
      periodStart: '2026-10-01',
      periodEnd: '2026-10-09',
      downloadUrl: 'https://x/signed',
      panelUrl: 'p',
    });
    expect(e.subject).toBe(
      'Süre uzatımı kanıt dosyası hazır · Tüm şantiyeler · Per 1 Eki – Cum 9 Eki',
    );
    expect(e.text).toContain('İndir (7 gün geçerli): https://x/signed');
    expect(e.text).toContain('Hava ve gecikmeler: p');
    expect(e.html).toContain('Tüm şantiyeler için Per 1 Eki – Cum 9 Eki kanıt dosyası hazır.');
    expect(e.html).toContain('Dosyayı indir');
  });

  it('weekly_digest: Turkish labels, percent and hours', () => {
    const e = weeklyDigestEmail({
      language: TR,
      orgName: 'Demir Yapı A.Ş.',
      weekStart: '2026-10-05',
      weekEnd: '2026-10-11',
      stats: {
        siteDays: 30,
        filed: 29,
        onTime: 27,
        weatherHoursBySite: [{ siteName: 'Kartal', hours: 3.5 }],
        unsigned: [],
        invoiceGaps: [{ companyName: 'Yıldız Elektrik', gap: 16 }],
        outboundCalls: { callDays: 4, filedByCall: 3 },
      },
      url: 'u',
    });
    expect(e.subject).toBe('TalkOlog haftalık · Pzt 5 Eki – Paz 11 Eki · %90 zamanında');
    expect(e.text).toContain('Zamanında: %90 (30 şantiye gününden 27 tanesi; 29 dosyalandı)');
    expect(e.text).toContain(
      'Hatırlatma aramaları: %75 aramada dosyalandı (TalkOlog’un aradığı 4 şantiye gününden 3 tanesi)',
    );
    expect(e.text).toContain('- Kartal: 3,5 sa');
    expect(e.text).toContain('- Yıldız Elektrik: +16 sa');
    expect(e.text).toContain('- Dosyalanan tüm raporlar onaylandı');
    expect(e.html).toContain('Haftalık özet');
  });

  it('unknown_contact and report_edited_after_signoff in Turkish', () => {
    const u = unknownContactEmail({
      language: TR,
      orgName: 'D',
      phone: null,
      snippet: null,
      url: 'u',
    });
    expect(u.subject).toBe('Bilinmeyen bir numara rapor göndermeye çalıştı');
    expect(u.text).toContain('Numara: bilinmeyen numara');
    expect(u.text).toContain('Mesaj: (metin yok)');
    expect(u.html).toContain('Ekip ve numaralar sayfasını aç');
    const e = reportEditedAfterSignoffEmail({
      language: TR,
      orgName: 'D',
      reportNo: 'KK-3307-0042',
      changeNote: '',
      version: 3,
      url: 'u',
    });
    expect(e.subject).toBe('KK-3307-0042 onaydan sonra düzenlendi');
    expect(e.text).toContain(
      'KK-3307-0042, siz onayladıktan sonra düzenlendi. Sürüm 3 yeniden onaylanmalı.',
    );
    expect(e.text).toContain('Değişiklik: (not yok)');
    expect(e.text).toContain('İncele: u');
    expect(e.html).toContain('Raporu incele');
    for (const x of [u, e]) {
      expect(x.html).not.toMatch(EMOJI);
      expect(x.html).toContain('TalkOlog tarafından sesli bir rapordan oluşturuldu.');
    }
  });

  it('English stays the default', () => {
    const e = reportEditedAfterSignoffEmail({
      orgName: 'K',
      reportNo: 'RL-2041-0187',
      changeNote: 'Apex 6 → 7',
      version: 2,
      url: 'u',
    });
    expect(e.text).toContain(
      'RL-2041-0187 was edited after you signed it off. Version 2 needs a fresh sign-off.',
    );
    expect(e.text).toContain('Change: Apex 6 → 7');
    expect(e.text).toContain('Review: u');
  });
});
