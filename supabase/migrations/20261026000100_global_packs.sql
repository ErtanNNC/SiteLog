do $$
declare
  v_us countries%rowtype;
  v_code text;
begin
  select * into v_us from countries where code = 'US';
  if v_us.whatsapp_sender_id is null then return; end if;
  for v_code in
    select code from countries
    where code not in ('US', 'TR') and whatsapp_sender_id is null
    order by code
  loop
    perform set_country_endpoints(v_code, null, null, v_us.whatsapp_sender_id,
                                  v_us.whatsapp_templates, null);
  end loop;
end $$;
