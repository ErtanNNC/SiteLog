-- TalkOlog · a country pack for every country (spec §19 Q379, decided by the owner 2026-10-26)
--
-- TalkOlog is global: the setup wizard lists every country, so every region the panel's phone
-- picker knows (libphonenumber) gets a row. US and TR keep their packs. Every other country gets
-- the same shared pack (packages/shared/src/countries-global.ts holds the same rows, and
-- supabase/db-tests keeps the two equal):
--
--   en-US, field {en-US} (Turkish off, §19 Q378); push then WhatsApp (SMS passive, §19 Q374);
--   Twilio, a long code type with no SMS sender, one-way, links allowed; no voice number;
--   no legal keys; USD (billed through Stripe like the US: billing_provider_for_country() makes
--   only TR manual); metric and A4 except LR and MM (imperial) and the US Letter countries;
--   the country's main IANA time zone.
--
-- Endpoints: the owner runs one Twilio WhatsApp number for every country (§19 Q370). Each new
-- pack takes this database's US WhatsApp sender and templates (the English ones), through the
-- audited set_country_endpoints() (country.endpoints_set, one row per pack), so WhatsApp works for
-- a new country's org as it does for a US org. A database whose US pack has no WhatsApp sender
-- (a local stack, CI) copies nothing. Later changes to the US endpoints are not copied: run
-- `pnpm whatsapp:templates -- --sync --code …` or `pnpm countries:set` for the other packs too.
--
-- Live database: about 240 small rows into a two-row table and as many audit rows.

