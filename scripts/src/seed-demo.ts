/**
 * Generates supabase/seed.sql from the §18 Kestrel demo dataset.
 *   pnpm seed:demo            → writes supabase/seed.sql
 *   pnpm seed:demo -- --stdout
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { kestrelDemo } from '@sitelog/shared/demo/kestrel.ts';
import { insertRows, lit } from './sql.ts';

export function buildSeedSql(): string {
  const d = kestrelDemo();
  const parts: string[] = [];
  parts.push(`-- SiteLog demo seed · Kestrel Build Group (§18). Generated by scripts/src/seed-demo.ts — do not edit by hand.
-- Demo office users sign in with magic links (or password "sitelog-demo" when password auth is enabled).
begin;
`);
  parts.push(`-- Office users ------------------------------------------------------------------------------
insert into auth.users (id, instance_id, email, aud, role, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, recovery_token, email_change, email_change_token_new)
values
${d.users
  .map(
    (u) =>
      `  (${lit(u.id)}, '00000000-0000-0000-0000-000000000000', ${lit(u.email)}, 'authenticated', 'authenticated', crypt('sitelog-demo', gen_salt('bf')), now(), '{"provider":"email","providers":["email"]}'::jsonb, ${lit({ name: u.name })}, now(), now(), '', '', '', '')`,
  )
  .join(',\n')}
on conflict (id) do nothing;

do $$
begin
  if exists (select 1 from pg_tables where schemaname = 'auth' and tablename = 'identities') then
${d.users
  .map(
    (u) =>
      `    insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
    values (gen_random_uuid(), ${lit(u.id)}, ${lit(u.id)}, ${lit({ sub: u.id, email: u.email })}, 'email', now(), now(), now()) on conflict do nothing;`,
  )
  .join('\n')}
  end if;
end $$;
`);
  parts.push(
    '-- Org -----------------------------------------------------------------------------------------',
  );
  parts.push(insertRows('orgs', [d.org]));
  parts.push(
    `delete from org_settings where org_id = ${lit(d.org.id)};\ndelete from companies where org_id = ${lit(d.org.id)};\n`,
  );
  parts.push(insertRows('org_members', d.members));
  parts.push(insertRows('org_settings', [d.settings]));
  parts.push(insertRows('sites', d.sites));
  parts.push(insertRows('reporters', d.reporters));
  parts.push(insertRows('site_reporters', d.siteReporters));
  parts.push(insertRows('site_recipients', d.recipients));
  parts.push(insertRows('companies', d.companies));
  parts.push(insertRows('glossary_terms', d.glossary));
  parts.push(
    '-- WhatsApp -------------------------------------------------------------------------------------',
  );
  parts.push(insertRows('conversations', d.conversations));
  parts.push(insertRows('messages', d.messages));
  parts.push(insertRows('transcripts', d.transcripts));
  parts.push(insertRows('unknown_senders', d.unknownSenders));
  parts.push(
    '-- Days, reports, versions ------------------------------------------------------------------------',
  );
  parts.push(
    insertRows(
      'site_days',
      d.siteDays.map((s) => ({ ...s, report_id: null })),
    ),
  );
  parts.push(insertRows('reports', d.reports));
  parts.push(
    d.siteDays
      .filter((s) => s.report_id)
      .map((s) => `update site_days set report_id = ${lit(s.report_id)} where id = ${lit(s.id)};`)
      .join('\n') + '\n',
  );
  parts.push(insertRows('report_versions', d.versions, { chunk: 25 }));
  parts.push(insertRows('uploads', d.uploads));
  parts.push(insertRows('report_sources', d.sources));
  parts.push(insertRows('manpower_entries', d.manpower));
  parts.push(insertRows('work_items', d.workItems));
  parts.push(insertRows('weather_events', d.weatherEvents, { omit: ['claim_ready'] }));
  parts.push(insertRows('questions', d.questions));
  parts.push(
    '-- Invoices, packs, notifications, audit ---------------------------------------------------------',
  );
  parts.push(insertRows('sub_invoices', d.invoices));
  parts.push(insertRows('evidence_packs', d.packs));
  parts.push(insertRows('notifications', d.notifications));
  parts.push(insertRows('audit_log', d.audit, { omit: ['id'] }));
  parts.push('commit;\n');
  return parts.join('\n');
}

const isMain = process.argv[1]?.endsWith('seed-demo.ts');
if (isMain) {
  const sql = buildSeedSql();
  if (process.argv.includes('--stdout')) {
    process.stdout.write(sql);
  } else {
    const out = join(import.meta.dirname, '..', '..', 'supabase', 'seed.sql');
    writeFileSync(out, sql);
    console.log(`wrote ${out} (${(sql.length / 1024).toFixed(0)} KB)`);
  }
}
