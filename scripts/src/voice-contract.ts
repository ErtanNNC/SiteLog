/**
 * `pnpm voice:contract` (W3-01): writes the voice contract for the Python agent from
 * `packages/shared` (spec §9.4, Appendix B):
 *
 *   apps/voice-agent/contract/<name>.json   JSON Schema of every voice schema (`VOICE_CONTRACT`)
 *   apps/voice-agent/contract/index.json    the routes (`VOICE_ROUTES`) and the call token header
 *   apps/voice-agent/copy/<language>.json   the spoken lines (`VOICE_CATALOGS`, EN/ES/TR)
 *   apps/voice-agent/copy/spoken.json       W4-07 (§19 Q245): the spoken-form policy, its lists
 *                                           (units, pronunciations, …) and every golden case of
 *                                           `speakable` the agent's port must say the same
 *   apps/voice-agent/copy/legal.json        W4-06 (§19 Q28): the packs' recording notices by key
 *                                           and language (`recordingNoticeLines`), the sentence a
 *                                           call says when the pack names one
 *
 * The files are checked in; the agent validates its requests and the answers against them (W3-02).
 * `pnpm voice:contract -- --check` writes nothing and exits 1 when a file differs, is missing or
 * is left over (CI runs it; `voice-contract.test.ts` checks the same in `pnpm check`).
 *
 * JSON Schema cannot carry Zod refinements (a weather day's `since`, "from or callId"): each
 * refined schema says its rule in its `description`, and the Python side checks it in code.
 */
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { z } from 'zod';
import {
  LANGUAGES,
  recordingNoticeLines,
  SPOKEN_ES_FEMININE,
  VOICE_RECORDING_NOTICE_VERSION,
  SPOKEN_FORM,
  SPOKEN_FORM_CASES,
  SPOKEN_PRONUNCIATIONS,
  SPOKEN_TR_ORDINAL_NOUNS,
  SPOKEN_UNITS,
  VOICE_API_ERRORS,
  VOICE_CALL_TOKEN_HEADER,
  VOICE_CATALOGS,
  VOICE_CONTRACT,
  VOICE_KEYS,
  VOICE_REQUEST_ID_HEADER,
  VOICE_ROUTES,
} from '@sitelog/shared';

const ROOT = resolve(import.meta.dirname, '..', '..');
/** Where the generated files go, relative to the repo root. */
export const VOICE_AGENT_DIR = 'apps/voice-agent';
const GENERATED_DIRS = [`${VOICE_AGENT_DIR}/contract`, `${VOICE_AGENT_DIR}/copy`];

const COMMENT =
  'Generated by `pnpm voice:contract` from packages/shared (voice.ts, copy/voice.*.ts). Do not edit.';
const LEGAL_COMMENT =
  'Generated by `pnpm voice:contract` from packages/shared (copy/legal). Do not edit.';

function json(value: unknown): string {
  return `${JSON.stringify(value, null, 2)}\n`;
}

/** Every generated file: repo-relative path → content. Pure and deterministic. */
export function voiceContractFiles(): Map<string, string> {
  const files = new Map<string, string>();
  for (const name of Object.keys(VOICE_CONTRACT).sort()) {
    const schema = z.toJSONSchema(VOICE_CONTRACT[name]!);
    files.set(
      `${VOICE_AGENT_DIR}/contract/${name}.json`,
      json({ $comment: COMMENT, title: name, ...schema }),
    );
  }
  files.set(
    `${VOICE_AGENT_DIR}/contract/index.json`,
    json({
      $comment: COMMENT,
      callTokenHeader: VOICE_CALL_TOKEN_HEADER,
      // W3-03: names a request (the same on its retry); field-api runs it once per call.
      requestIdHeader: VOICE_REQUEST_ID_HEADER,
      auth: 'Authorization: Bearer VOICE_AGENT_TOOL_SECRET on every route',
      routes: VOICE_ROUTES,
      // W3-03: the `error` codes field-api answers on /voice/*.
      errors: VOICE_API_ERRORS,
    }),
  );
  for (const language of LANGUAGES) {
    const catalog = VOICE_CATALOGS[language];
    const lines = Object.fromEntries(VOICE_KEYS.map((key) => [key, catalog[key]]));
    files.set(
      `${VOICE_AGENT_DIR}/copy/${language}.json`,
      json({ $comment: COMMENT, language, lines }),
    );
  }
  // W4-07 (§19 Q245): what `speakable()` knows, for the agent's port (sitelog_voice/spoken.py).
  files.set(
    `${VOICE_AGENT_DIR}/copy/spoken.json`,
    json({
      $comment: COMMENT,
      policy: SPOKEN_FORM,
      pronunciations: SPOKEN_PRONUNCIATIONS,
      units: SPOKEN_UNITS,
      esFeminine: SPOKEN_ES_FEMININE,
      trOrdinalNouns: SPOKEN_TR_ORDINAL_NOUNS,
      cases: SPOKEN_FORM_CASES.map(([language, written, spoken]) => ({
        language,
        written,
        spoken,
      })),
    }),
  );
  // W4-06 (§19 Q28): the recording notice a pack names, by key and language; the agent says it
  // (else `fallback`, its own line) and reports the version said with the disclosure mark.
  files.set(
    `${VOICE_AGENT_DIR}/copy/legal.json`,
    json({
      $comment: LEGAL_COMMENT,
      fallback: VOICE_RECORDING_NOTICE_VERSION,
      recordingNotices: recordingNoticeLines(),
    }),
  );
  return files;
}

/** Files on disk under the generated directories (repo-relative). */
function existingFiles(root: string): string[] {
  const out: string[] = [];
  for (const dir of GENERATED_DIRS) {
    const abs = join(root, dir);
    if (!existsSync(abs)) continue;
    for (const f of readdirSync(abs)) if (f.endsWith('.json')) out.push(`${dir}/${f}`);
  }
  return out;
}

/** The differences between the generated files and the disk: changed, missing, left over. */
export function voiceContractDrift(root: string = ROOT): string[] {
  const files = voiceContractFiles();
  const problems: string[] = [];
  for (const [path, content] of files) {
    const abs = join(root, path);
    if (!existsSync(abs)) problems.push(`missing: ${path}`);
    else if (readFileSync(abs, 'utf8') !== content) problems.push(`differs: ${path}`);
  }
  for (const path of existingFiles(root)) {
    if (!files.has(path)) problems.push(`left over: ${path}`);
  }
  return problems;
}

/** Writes every file and removes left-over ones; answers the paths written. */
export function writeVoiceContract(root: string = ROOT): string[] {
  const files = voiceContractFiles();
  for (const path of existingFiles(root)) if (!files.has(path)) rmSync(join(root, path));
  const written: string[] = [];
  for (const [path, content] of files) {
    const abs = join(root, path);
    mkdirSync(dirname(abs), { recursive: true });
    if (existsSync(abs) && readFileSync(abs, 'utf8') === content) continue;
    writeFileSync(abs, content);
    written.push(path);
  }
  return written;
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) {
  if (process.argv.includes('--check')) {
    const drift = voiceContractDrift();
    if (drift.length > 0) {
      console.error(
        `The voice contract is out of date; run \`pnpm voice:contract\`:\n  ${drift.join('\n  ')}`,
      );
      process.exit(1);
    }
    console.log(`Voice contract up to date (${voiceContractFiles().size} files).`);
  } else {
    const written = writeVoiceContract();
    console.log(
      written.length === 0
        ? `Voice contract unchanged (${voiceContractFiles().size} files).`
        : `Wrote ${written.length} file(s):\n  ${written.join('\n  ')}`,
    );
  }
}
